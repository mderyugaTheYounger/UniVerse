/**
 * Degree types for majors as specified in requirements ('BA', 'BS', 'other').
 */
export type DegreeType = 'BA' | 'BS' | 'other' | (string & {});

// ============================================================================
// Table Schema Interfaces
// ============================================================================

/**
 * Departments table schema
 * Represents academic departments (e.g., alpha code 'ITSC' -> Computer Science).
 */
export interface DepartmentTable {
  /** Alpha code primary key (e.g., 'ITSC', 'MATH') */
  alpha_code: string;
  /** Full name of the department */
  department_name: string;
}

/**
 * Courses table schema
 * Represents individual courses offered by departments.
 */
export interface CourseTable {
  /** Unique course UUID identifier (generated by default using gen_random_uuid()) */
  course_id: Generated<string>;
  /** Department alpha code foreign key (e.g., 'ITSC') */
  alpha_code: string;
  /** Numeric course code (e.g., '2175') */
  numeric_code: string;
  /** Course title */
  title: string;
  /** Detailed course description */
  description: string | null;
  /** Number of credit hours for the course */
  credit_hours: number;
}

/**
 * Majors table schema
 * Represents academic majors associated with departments.
 */
export interface MajorTable {
  /** Unique major UUID identifier (generated by default using gen_random_uuid()) */
  major_id: Generated<string>;
  /** Department alpha code foreign key */
  alpha_code: string;
  /** Major title (e.g., 'Computer Science') */
  title: string;
  /** Major description */
  description: string | null;
  /** Degree type: 'BA', 'BS', 'other' */
  type: DegreeType;
}

/**
 * Minors table schema
 * Represents academic minors associated with departments.
 */
export interface MinorTable {
  /** Unique minor UUID identifier (generated by default using gen_random_uuid()) */
  minor_id: Generated<string>;
  /** Department alpha code foreign key */
  alpha_code: string;
  /** Minor title (e.g., 'Software Engineering') */
  title: string;
  /** Minor description */
  description: string | null;
}

/**
 * Major Requirements junction table schema
 * Maps many-to-many relationship between Majors and Courses.
 */
export interface MajorRequirementTable {
  /** Major UUID foreign key */
  major_id: string;
  /** Course UUID foreign key */
  course_id: string;
}

/**
 * Minor Requirements junction table schema
 * Maps many-to-many relationship between Minors and Courses.
 */
export interface MinorRequirementTable {
  /** Minor UUID foreign key */
  minor_id: string;
  /** Course UUID foreign key */
  course_id: string;
}

/**
 * Prerequisites junction table schema
 * Maps course prerequisites (Course -> Required Prerequisite Course).
 */
export interface PrerequisiteTable {
  /** The course that requires the prerequisite */
  course_id: string;
  /** The course that is required as a prerequisite */
  required_course_id: string;
}

