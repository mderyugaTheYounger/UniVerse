/**
 * Creates and configures a Kysely instance connected to PostgreSQL.
 *
 * @param config - PostgreSQL PoolConfig, connection string URI, or existing pg.Pool instance
 * @returns Fully typed Kysely<CourseDatabase> instance
 *
 * @example
 * ```ts
 * const db = createCourseDB({
 *   connectionString: process.env.DATABASE_URL,
 * });
 *
 * const courses = await db.selectFrom('courses').selectAll().execute();
 * ```
 */
export function createCourseDB(config?: PoolConfig | string | Pool): Kysely<CourseDatabase> {
  let pool: Pool;
  if (config instanceof Pool) {
    pool = config;
  } else if (typeof config === 'string') {
    pool = new Pool({ connectionString: config });
  } else {
    pool = new Pool(config);
  }

  return new Kysely<CourseDatabase>({
    dialect: new PostgresDialect({
      pool,
    }),
  });
}
